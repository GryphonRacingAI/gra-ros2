#!/usr/bin/env python3
"""Cheap dynamic cones: a small pool of rigid cone bodies that is moved to wherever the car is.

Why: a dynamic cone resting on the ground costs a persistent contact every physics step. With ~300
cones that cut the real-time factor of the 4-core WSL VM from ~0.92 to ~0.57. Only the few cones
near the car can be hit, so only those need to be dynamic.

The track world (<track>.sdf, generated by xacro) holds
  * every cone as a static, visual-only model (blue_1, yellow_7, large_orange_2, ...): what lidar
    and camera see, no collision;
  * a pool of dynamic cone bodies with collision (dyn_blue_1, dyn_yellow_3, ...), parked far away.
This node teleports (Gazebo set_pose, so nothing is created or removed and the sensors never lose a
cone) a free pooled body of the same type onto each cone the car comes within `activate` m of and
moves the static visual 10 m underground. The body is then a normal rigid body: the car can push or
knock it over, and it is the cone as far as everybody can see. Once the car is more than `release`
m away and the body has rested for `rest` s, the static visual is put back at the body's final pose
(so a knocked-over cone stays knocked over) and the body goes back into the pool. A cone that has
been moved is activated again from its new pose on the next lap.

While a cone is active its pose is that of its dyn_* body and the blue_N model sits underground.
Poses come from Gazebo's dynamic_pose topic; only Gazebo transport is used, no ROS.
FSAI_DYNAMIC_CONES=0 disables the node (cones then have no collision at all).

usage: cone_activator.py <track.sdf> [--world sim_world] [--activate 7] [--release 12] [--rest 1.5]
"""
import argparse
import math
import os
import re
import sys
import threading
import time
import xml.etree.ElementTree as ET

from gz.msgs10.boolean_pb2 import Boolean
from gz.msgs10.pose_pb2 import Pose
from gz.msgs10.pose_v_pb2 import Pose_V
from gz.transport13 import Node

CONE_RE = re.compile(r'^(blue|yellow|orange|large_orange)_\d+$')
POOL_RE = re.compile(r'^dyn_(blue|yellow|orange|large_orange)_\d+$')
HIDE_Z = -10.0


def rpy_to_quat(r, p, y):
    cr, sr, cp, sp, cy, sy = (math.cos(r / 2), math.sin(r / 2), math.cos(p / 2), math.sin(p / 2),
                              math.cos(y / 2), math.sin(y / 2))
    return (sr * cp * cy - cr * sp * sy, cr * sp * cy + sr * cp * sy,
            cr * cp * sy - sr * sp * cy, cr * cp * cy + sr * sp * sy)


class Item:
    """A cone or a pool body: name, type, pose = (x, y, z, qx, qy, qz, qw)."""

    def __init__(self, elem):
        self.name = elem.get('name')
        self.type = re.sub(r'^dyn_|_\d+$', '', self.name)
        v = [float(t) for t in elem.find('pose').text.split()]
        self.pose = tuple(v[:3]) + rpy_to_quat(*v[3:6])
        self.home = self.pose  # parking place of a pool body
        self.body = None       # cone: name of the pool body while active
        self.cone = None       # pool body: name of the cone it stands in for
        self.last_moved = 0.0  # sim time the pose last changed by more than ~2 mm (pool body)
        self.ref = self.pose   # pose at last_moved


class Activator:
    def __init__(self, a):
        self.a = a
        world = ET.parse(a.track).getroot().find('world')
        self.cones, self.pool = {}, {}
        for m in world.iter('model'):
            n = m.get('name', '')
            if m.find('pose') is None:
                continue
            if CONE_RE.match(n):
                self.cones[n] = Item(m)
            elif POOL_RE.match(n):
                self.pool[n] = Item(m)
        self.free = {}
        for b in self.pool.values():
            self.free.setdefault(b.type, []).append(b.name)
        self.node = Node()
        self.lock = threading.Lock()
        self.car = None
        self.now = 0.0
        self.warned = set()
        print('cone_activator: %d cones, pool %s from %s' % (
            len(self.cones), {k: len(v) for k, v in self.free.items()}, a.track), flush=True)

    # -- gazebo side -------------------------------------------------------------------------
    def on_pose(self, msg):
        t = msg.header.stamp.sec + msg.header.stamp.nsec * 1e-9
        with self.lock:
            self.now = max(self.now, t)
            for p in msg.pose:
                if p.name == 'ads_dv':
                    self.car = (p.position.x, p.position.y)
                    continue
                b = self.pool.get(p.name)
                if b is not None and b.cone is not None:
                    q = p.orientation
                    b.pose = (p.position.x, p.position.y, p.position.z, q.x, q.y, q.z, q.w)
                    r = b.ref  # a body at rest still reports sub-millimetre jitter
                    if (math.dist(b.pose[:3], r[:3]) > 0.002
                            or abs(sum(x * y for x, y in zip(b.pose[3:], r[3:]))) < 0.99999):
                        b.ref, b.last_moved = b.pose, t

    def set_pose(self, name, pose):
        req = Pose()
        req.name = name
        req.position.x, req.position.y, req.position.z = pose[:3]
        req.orientation.x, req.orientation.y, req.orientation.z, req.orientation.w = pose[3:]
        for _ in range(3):
            ok, rep = self.node.request('/world/%s/set_pose' % self.a.world, req, Pose, Boolean, 2000)
            if ok and rep.data:
                return True
            time.sleep(0.1)
        print('cone_activator: set_pose %s failed' % name, flush=True)
        return False

    def activate(self, c):
        free = self.free.get(c.type)
        if not free:
            if c.type not in self.warned:
                self.warned.add(c.type)
                print('cone_activator: pool of %s cones is empty' % c.type, flush=True)
            return False
        b = self.pool[free.pop()]
        # body first, then hide the visual: at worst both are seen for a frame
        self.set_pose(b.name, c.pose)
        self.set_pose(c.name, c.pose[:2] + (HIDE_Z,) + c.pose[3:])
        with self.lock:
            b.cone, b.pose, b.ref, b.last_moved, c.body = c.name, c.pose, c.pose, self.now, b.name
        return True

    def release(self, c):
        b = self.pool[c.body]
        c.pose = b.pose
        self.set_pose(c.name, c.pose)
        self.set_pose(b.name, b.home)
        with self.lock:
            b.cone, c.body = None, None
            self.free[b.type].append(b.name)

    def run(self):
        if not self.node.subscribe(Pose_V, '/world/%s/dynamic_pose/info' % self.a.world, self.on_pose):
            print('cone_activator: cannot subscribe to dynamic_pose', file=sys.stderr)
            return 1
        ra2, rr2 = self.a.activate ** 2, self.a.release ** 2
        last_report, n_act, n_rel = time.time(), 0, 0
        while True:
            time.sleep(0.05)
            with self.lock:
                car, now = self.car, self.now
                todo = []
                if car is not None:
                    for c in self.cones.values():
                        if c.body is None:
                            d2 = (c.pose[0] - car[0]) ** 2 + (c.pose[1] - car[1]) ** 2
                            if d2 < ra2:
                                todo.append((d2, c, True))
                        else:
                            b = self.pool[c.body]
                            d2 = (b.pose[0] - car[0]) ** 2 + (b.pose[1] - car[1]) ** 2
                            if d2 > rr2 and now - b.last_moved > self.a.rest:
                                todo.append((d2, c, False))
            todo.sort(key=lambda t: t[0])
            for _, c, act in todo:
                if act:
                    n_act += self.activate(c)
                else:
                    self.release(c)
                    n_rel += 1
            if time.time() - last_report > 30:
                last_report = time.time()
                print('cone_activator: %d active, %d activations, %d releases so far' % (
                    sum(c.body is not None for c in self.cones.values()), n_act, n_rel), flush=True)


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('track')
    ap.add_argument('--world', default='sim_world')
    ap.add_argument('--activate', type=float, default=7.0)
    ap.add_argument('--release', type=float, default=12.0)
    ap.add_argument('--rest', type=float, default=1.5)
    a, _ = ap.parse_known_args()
    if os.environ.get('FSAI_DYNAMIC_CONES', '1') == '0':
        print('cone_activator: disabled (FSAI_DYNAMIC_CONES=0), cones have no collision', flush=True)
        sys.exit(0)
    try:
        sys.exit(Activator(a).run())
    except KeyboardInterrupt:
        pass
